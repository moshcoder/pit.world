/** How many matches a search ranks: GIN hands them over unordered, so this bounds the work. */
const SEARCH_SCAN = 3_000
/** How many matches a search for one kind of page looks through (the SQLite store's KIND_SCAN). */
const KIND_SCAN = 8_000
/** Each search query's own limit; the AND query and the OR fallback together stay inside pit.world's 2.5 s. */
const SEARCH_TIMEOUT_MS = 1_100
/** Longer than any write may run, so an id this old belongs to a committed (or abandoned) row. */
const WRITE_TIMEOUT_MS = 30_000
/** A btree entry holds ~2.7 kB; a longer address cannot be keyed, and would fail its whole batch. */
const MAX_URL_BYTES = 2_048
/** ts_rank weights {D, C, B, A}: body, description and site, keywords, title (bm25 10/6/4/3/1 in SQLite). */
const WEIGHTS = '{0.1,0.4,0.6,1.0}'

/** Postgres text cannot hold NUL; a page with one in it must not fail its batch. */
const clean = (value: string) => (value.includes('\u0000') ? value.replace(/\u0000/g, '') : value)
const cleanOrNull = (value: string | null) => (value === null ? null : clean(value))

/** User words as a websearch_to_tsquery string that means "all of them": each token quoted, so `or` and `-` stay words. */
export function websearchAll(terms: string[]): string {
  return terms.join(' ')
}
export function websearchAny(terms: string[]): string {
  return terms.join(' or ')
}

/** /api/corpus `q` as websearch syntax: commas separate alternatives, words in one part all appear (& binds before |). */
export function corpusWebsearch(input: string): string | null {
  const parts = String(input ?? '')
    .split(',')
    .map((part) => toFtsTerms(part))
    .filter((terms) => terms.length)
    .slice(0, 16)
  if (!parts.length) return null
  return parts.map((terms) => terms.join(' ')).join(' or ')
}

const TSV = `
  setweight(to_tsvector('simple'::regconfig, title), 'A') ||
  setweight(to_tsvector('simple'::regconfig, keywords), 'B') ||
  setweight(to_tsvector('simple'::regconfig, description || ' ' || site || ' ' || replace(site, '.', ' ')), 'C') ||
  setweight(to_tsvector('simple'::regconfig, body), 'D')`

