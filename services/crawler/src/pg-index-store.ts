/**
 * The local search mirror in Postgres, for when one SQLite writer is not enough.
 *
 * SQLite takes one writer at a time, and at ~63 pages/s that writer was the crawl's
 * ceiling; a million pages an hour is ~280/s. Here any number of publishing processes
 * write at once: a batch is one INSERT ... ON CONFLICT (url) DO UPDATE over unnest()ed
 * array literals, and the page counter moves in the same statement. CRAWL_INDEX_DATABASE_URL
 * selects it; unset, the crawler keeps the SQLite IndexStore (tests and laptops).
 *
 * Same tables as the SQLite file, in the role's default schema (nothing here names a
 * schema): pages (with a stored, weighted `tsvector` and a GIN index), page_policy,
 * page_cards, policy_site_checks and index_meta (counters and cursors).
 *
 * What differs, on purpose:
 *  - Search ranks a bounded candidate set (the first SEARCH_SCAN matches the GIN index
 *    yields) with ts_rank, instead of bm25 over every match: a common word has millions,
 *    and pit.world gives an engine 2.5 s. Each search also runs under a statement timeout.
 *  - Ids are handed out by a sequence, and concurrent writers commit out of id order. A
 *    corpus scan therefore stops at the newest id at least `corpusLagMs` old, so a harvest
 *    cursor never runs past a page that is still being written.
 *  - Postgres files do not shrink when rows go: freed space is reused by later inserts. So
 *    the byte budget is kept on the live pages (count x bytes a page), not the file size;
 *    see trim().
 */
