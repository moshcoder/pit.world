/**
 * Full-text reads go through the GIN index and nothing else. A word in most pages makes a
 * sequential scan look cheap to the planner, but every row it reads then decompresses a
 * tsvector of several kB to test it (seconds, cold, at 70k pages); a bitmap from the GIN index
 * needs no such test unless it turns lossy, which a larger work_mem puts off. Likewise an id
 * range is read as a bitmap, not by walking the primary key and testing each row in it.
 */
async function fullTextPlan(tx: SQL) {
  await tx.unsafe('set local enable_seqscan = off')
  await tx.unsafe('set local enable_indexscan = off')
  await tx.unsafe(`set local work_mem = '32MB'`)
}

const isRetryable = (error: unknown) => /deadlock detected|could not serialize access/i.test(String((error as Error)?.message ?? error))
const isTimeout = (error: unknown) => /statement timeout|canceling statement/i.test(String((error as Error)?.message ?? error))

export class PgIndexStore implements SearchIndex {
  private sql: SQL
  private ready: Promise<void> | null = null
  readonly maxBytes: number
  /** Freed space is reused, never returned: trim() bounds the live pages, see there. */
  readonly reclaims = true
  lastAddAt: string | null = null
  private readonly corpusLagMs: number
  private sizeCache: { at: number; value: number } | null = null
  private countCache: { at: number; value: number } | null = null
  private statsCache: { at: number; value: Record<string, unknown> } | null = null
  private refreshing: Promise<unknown> | null = null

  constructor(url: string, maxBytes = 0, options: { max?: number; corpusLagMs?: number } = {}) {
    this.maxBytes = maxBytes > 0 ? maxBytes : 0
    this.corpusLagMs = Math.max(0, options.corpusLagMs ?? 60_000)
    // prepare: false, so every query is planned with its own values: a generic plan for
    // `fts @@ $1` cannot tell a rare word from a common one.
    this.sql = new SQL({ url, max: options.max ?? 8, idleTimeout: 60, prepare: false })
  }

  private init() {
    this.ready ??= this.sql
      .begin(async (tx: SQL) => {
        // Several processes start at once; CREATE ... IF NOT EXISTS races itself without this.
        await tx.unsafe(`select pg_advisory_xact_lock(hashtext('pitcrawl-index-schema'))`)
        for (const statement of SCHEMA) await tx.unsafe(statement)
      })
      .then(() => undefined)
      .catch((error) => {
        this.ready = null
        throw error
      })
    return this.ready
  }

  /** A transaction whose statements each give up after `ms`. */
  private async timed<T>(ms: number, run: (tx: SQL) => Promise<T>, fullText = false): Promise<T> {
    await this.init()
    return (await this.sql.begin(async (tx: SQL) => {
      await tx.unsafe(`set local statement_timeout = ${Math.max(1, Math.trunc(ms))}`)
      if (fullText) await fullTextPlan(tx)
      return run(tx)
    })) as T
  }

  /** Writes retry a deadlock or serialization failure: losing the batch means losing the work that made it. */
  private async write<T>(ms: number, run: (tx: SQL) => Promise<T>, attempts = 4): Promise<T> {
    for (let attempt = 1; ; attempt++) {
      try {
        return await this.timed(ms, run)
      } catch (error) {
        if (attempt >= attempts || !isRetryable(error)) throw error
        await Bun.sleep(50 * attempt + Math.floor(Math.random() * 50))
      }
    }
  }

  private async meta(key: string): Promise<number | null> {
    await this.init()
    // threatcrush-disable-next-line sql-template-interpolation  Bun's sql tagged template binds ${} as parameters; nothing is concatenated
    const rows = (await this.sql`select n from index_meta where k = ${key}`) as { n: string | number }[]
    return rows.length ? Number(rows[0]!.n) : null
  }

  private async setMeta(key: string, value: number): Promise<void> {
    await this.init()
    // threatcrush-disable-next-line sql-template-interpolation  Bun's sql tagged template binds ${} as parameters; nothing is concatenated
    await this.sql`insert into index_meta (k, n) values (${key}, ${value}) on conflict (k) do update set n = excluded.n`
  }

  /** Keep a batch: one statement for every page, policy row, card and the page counter. */
  async add(entries: Array<IndexedRecord | string>): Promise<number> {
    const rows: PageRow[] = []
    for (const raw of entries) {
      const row = pageRowOf(raw)
      if (row && Buffer.byteLength(row.url) <= MAX_URL_BYTES) rows.push(row)
    }
    if (!rows.length) return 0
    // ON CONFLICT DO UPDATE cannot touch one row twice in a statement: the last copy wins,
    // as it would have in a loop. Sorted, so concurrent batches lock rows in one order.
    const pages = [...new Map(rows.map((r) => [r.url, r])).values()].sort((a, b) => (a.url < b.url ? -1 : a.url > b.url ? 1 : 0))
    const cards = pages.filter((p) => p.card)
    const col = <T extends string | number | null>(pick: (p: PageRow) => T) => pgArray(pages.map(pick))
    await this.write(WRITE_TIMEOUT_MS, async (tx) => {
      await tx`
        with input as (
          select * from unnest(
            ${col((p) => clean(p.url))}::text[], ${col((p) => clean(p.site))}::text[], ${col((p) => clean(p.kind))}::text[],
            ${col((p) => clean(p.title))}::text[], ${col((p) => clean(p.description))}::text[], ${col((p) => clean(p.keywords))}::text[],
            ${col((p) => clean(p.body))}::text[], ${col((p) => cleanOrNull(p.language))}::text[], ${col((p) => clean(p.fetched))}::text[],
            ${col((p) => p.train)}::smallint[], ${col((p) => cleanOrNull(p.reason))}::text[], ${col((p) => p.source)}::text[]
          ) as t(url, site, kind, title, description, keywords, body, language, fetched, train, reason, source)
        ), up as (
          insert into pages (url, site, kind, title, description, keywords, body, language, fetched_at)
          select url, site, kind, title, description, keywords, body, language, fetched from input order by url
          on conflict (url) do update set site = excluded.site, kind = excluded.kind, title = excluded.title,
            description = excluded.description, keywords = excluded.keywords, body = excluded.body,
            language = excluded.language, fetched_at = excluded.fetched_at
          returning id, url, (xmax = 0) as inserted
        ), pol as (
          -- A record without a verdict (queued by an older crawler) keeps whatever was decided before.
          insert into page_policy (id, site, kind, language, fetched_at, train, reason, source)
          select up.id, i.site, i.kind, i.language, i.fetched, i.train, i.reason, i.source from up join input i using (url) order by up.id
          on conflict (id) do update set site = excluded.site, kind = excluded.kind, language = excluded.language,
            fetched_at = excluded.fetched_at,
            train = case when excluded.source = 'crawl' then excluded.train else page_policy.train end,
            reason = case when excluded.source = 'crawl' then excluded.reason else page_policy.reason end,
            source = case when excluded.source = 'crawl' then 'crawl' else page_policy.source end
        ), cards as (
          insert into page_cards (url, image, price)
          select url, image, price from unnest(
            ${pgArray(cards.map((p) => clean(p.url)))}::text[], ${pgArray(cards.map((p) => cleanOrNull(p.card!.image)))}::text[], ${pgArray(cards.map((p) => cleanOrNull(p.card!.price)))}::text[]
          ) as c(url, image, price) order by url
          on conflict (url) do update set image = excluded.image, price = excluded.price
        ), live as (
          update index_meta set n = n + (select count(*) from up where inserted) where k = 'pages_live'
        )
        select count(*) from up`
    })
    this.countCache = null
    this.lastAddAt = new Date().toISOString()
    return rows.length
  }

  /**
   * Moves the id sequence past `maxId` (never back), so pages the crawl writes from now on take
   * ids above every id a migration will bring. Call before load().
   */
  async reserveIds(maxId: number): Promise<void> {
    await this.init()
    await this.sql`select setval(pg_get_serial_sequence('pages', 'id'), greatest(nextval(pg_get_serial_sequence('pages', 'id')), ${Math.max(1, Math.trunc(maxId))}::bigint))`
  }

  /**
   * Bulk load from an old SQLite index with ids kept (migrate-index). A page already here (by
   * address) wins. A page whose id was taken by one the crawl wrote here before reserveIds()
   * gets a fresh id instead, so nothing is lost to a collision. The cursor moves in the same
   * statement, so a batch and its place in the run land together or not at all.
   */
  async load(rows: MigratedPage[], cursor?: { key: string; value: number }): Promise<number> {
    rows = rows.filter((r) => Buffer.byteLength(r.url) <= MAX_URL_BYTES)
    if (!rows.length && !cursor) return 0
    const col = <T extends string | number | null>(pick: (p: MigratedPage) => T) => pgArray(rows.map(pick))
    const out = await this.write(WRITE_TIMEOUT_MS * 4, async (tx) => {
      return (await tx`
        with raw as (
          select * from unnest(
            ${col((p) => p.id)}::bigint[], ${col((p) => clean(p.url))}::text[], ${col((p) => clean(p.site))}::text[], ${col((p) => clean(p.kind))}::text[],
            ${col((p) => clean(p.title))}::text[], ${col((p) => clean(p.description ?? ''))}::text[], ${col((p) => clean(p.keywords ?? ''))}::text[],
            ${col((p) => clean(p.body ?? ''))}::text[], ${col((p) => cleanOrNull(p.language))}::text[], ${col((p) => clean(p.fetched_at))}::text[],
            ${col((p) => p.train)}::smallint[], ${col((p) => cleanOrNull(p.reason))}::text[], ${col((p) => p.source ?? 'legacy')}::text[]
          ) as t(id, url, site, kind, title, description, keywords, body, language, fetched, train, reason, source)
        ), input as materialized (
          select r.*, case when exists (select 1 from pages p where p.id = r.id) then nextval(pg_get_serial_sequence('pages', 'id')) else r.id end as nid
          from raw r where not exists (select 1 from pages p where p.url = r.url)
        ), ins as (
          insert into pages (id, url, site, kind, title, description, keywords, body, language, fetched_at)
          select nid, url, site, kind, title, description, keywords, body, language, fetched from input order by nid
          on conflict do nothing
          returning id
        ), pol as (
          insert into page_policy (id, site, kind, language, fetched_at, train, reason, source)
          select i.nid, i.site, i.kind, i.language, i.fetched, i.train, i.reason, i.source from input i join ins on ins.id = i.nid
          on conflict (id) do nothing
        ), live as (
          update index_meta set n = n + (select count(*) from ins) where k = 'pages_live'
        ), cur as (
          insert into index_meta (k, n) select ${cursor?.key ?? 'migrate_cursor'}, ${cursor?.value ?? 0}::bigint where ${Boolean(cursor)}::boolean
          on conflict (k) do update set n = excluded.n
        )
        select count(*)::int as n from ins`) as { n: number }[]
    })
    this.countCache = null
    return Number(out[0]?.n ?? 0)
  }

  /** Cards from an old SQLite index (migrate-index): a card already here wins. */
  async loadCards(rows: Array<{ url: string; image: string | null; price: string | null }>): Promise<void> {
    rows = rows.filter((r) => Buffer.byteLength(r.url) <= MAX_URL_BYTES)
    if (!rows.length) return
    await this.init()
    await this.sql`
      insert into page_cards (url, image, price)
      select * from unnest(${pgArray(rows.map((r) => clean(r.url)))}::text[], ${pgArray(rows.map((r) => cleanOrNull(r.image)))}::text[], ${pgArray(rows.map((r) => cleanOrNull(r.price)))}::text[])
      on conflict (url) do nothing`
  }

  async loadSiteChecks(rows: Array<{ site: string; checked_at: number }>): Promise<void> {
    if (!rows.length) return
    await this.init()
    await this.sql`
      insert into policy_site_checks (site, checked_at)
      select * from unnest(${pgArray(rows.map((r) => clean(r.site)))}::text[], ${pgArray(rows.map((r) => r.checked_at))}::bigint[])
      on conflict (site) do update set checked_at = greatest(policy_site_checks.checked_at, excluded.checked_at)`
  }

  async cursor(key: string): Promise<number | null> {
    return this.meta(key)
  }

  async setCursor(key: string, value: number | null): Promise<void> {
    if (value === null) {
      await this.init()
      // threatcrush-disable-next-line sql-template-interpolation  Bun's sql tagged template binds ${} as parameters; nothing is concatenated
      await this.sql`delete from index_meta where k = ${key}`
    } else await this.setMeta(key, value)
  }

  // ---- the byte budget ---------------------------------------------------------------

  private async measureSize(): Promise<number> {
    await this.init()
    const parts = TABLES.map((t) => `pg_total_relation_size('${t}'::regclass)`).join(' + ')
    const out = (await this.sql.unsafe(`select (${parts})::bigint as n`)) as { n: string | number }[]
    return Number(out[0]?.n ?? 0)
  }

  /**
   * Bytes on disk, from the catalogue (no scan). /stats asks on every request: a cached
   * figure comes back at once and a stale one is refreshed behind it, so a slow database
   * costs /stats a slightly old number, never a wait. `0` asks for it fresh.
   */
  async sizeBytes(maxAgeMs = 5_000): Promise<number> {
    const now = Date.now()
    if (maxAgeMs > 0 && this.sizeCache) {
      if (now - this.sizeCache.at >= maxAgeMs) this.refresh()
      return this.sizeCache.value
    }
    const value = await this.measureSize()
    this.sizeCache = { at: Date.now(), value }
    return value
  }

  /** Pages kept, from the counter add() and trim() keep: cached like sizeBytes. */
  async count(maxAgeMs = 2_000): Promise<number> {
    const now = Date.now()
    if (maxAgeMs > 0 && this.countCache) {
      if (now - this.countCache.at >= maxAgeMs) this.refresh()
      return this.countCache.value
    }
    const value = Math.max(0, (await this.meta('pages_live')) ?? 0)
    this.countCache = { at: Date.now(), value }
    return value
  }

  private refresh() {
    this.refreshing ??= Promise.all([this.measureSize(), this.meta('pages_live')])
      .then(([size, live]) => {
        this.sizeCache = { at: Date.now(), value: size }
        this.countCache = { at: Date.now(), value: Math.max(0, live ?? 0) }
      })
      .catch(() => {})
      .finally(() => {
        this.refreshing = null
      })
  }

  /** The page counter made exact again (count(*): seconds on millions of rows, never on a hot path). */
  async resync(): Promise<number> {
    await this.init()
    await this.sql`update index_meta set n = (select count(*) from pages) where k = 'pages_live'`
    this.countCache = null
    return this.count(0)
  }

  /**
   * Keeps the live pages inside the budget, oldest (by fetched_at) first, in batches.
   *
   * Unlike SQLite's incremental vacuum, deleting rows here never shrinks a file: vacuum marks
   * the space free and later inserts reuse it. Trimming until the file is under budget would
   * therefore delete everything. Instead the budget is applied to the live pages: bytes a page
   * = file size / pages, measured whenever the files have grown (growth means no free space
   * was left, so the ratio is honest), and pages are dropped until pages x bytes a page fits.
   * The files then stop growing at about the budget. A budget lowered below what the files
   * already take frees room inside them; only VACUUM FULL or pg_repack gives it back to the disk.
   *
   * Any number of processes may run this: each batch takes a transaction-level advisory lock,
   * re-reads the counter and skips rows a writer holds.
   */
  async trim(options: TrimOptions = {}): Promise<TrimResult> {
    const batch = Math.max(1, Math.trunc(options.batch ?? 2_000))
    const maxBatches = Math.max(1, Math.trunc(options.maxBatches ?? 50))
    const keepMin = Math.max(0, Math.trunc(options.keepMin ?? 1_000))
    const idle = options.sleep ?? ((ms: number) => new Promise<void>((resolve) => setTimeout(resolve, ms)))
    const bytesBefore = await this.sizeBytes(0)
    const live = await this.count(0)
    if (!this.maxBytes) return { deleted: 0, bytesBefore, bytesAfter: bytesBefore, done: true, reclaims: true }
    const lastSize = await this.meta('trim_size')
    let perPage = await this.meta('trim_bytes_per_page')
    if (live > 0 && (perPage === null || lastSize === null || bytesBefore > lastSize)) {
      perPage = Math.max(1, Math.ceil(bytesBefore / live))
      await this.setMeta('trim_bytes_per_page', perPage)
      await this.setMeta('trim_size', bytesBefore)
    }
    if (!perPage || live * perPage <= this.maxBytes) return { deleted: 0, bytesBefore, bytesAfter: bytesBefore, done: true, reclaims: true, liveBytes: live * (perPage ?? 0) }
    const target = Math.max(keepMin, Math.floor(this.maxBytes / perPage))
    let deleted = 0
    for (let round = 0; round < maxBatches; round++) {
      const gone = await this.write(WRITE_TIMEOUT_MS, async (tx) => {
        const lock = (await tx`select pg_try_advisory_xact_lock(hashtext('pitcrawl-index-trim')) as ok`) as { ok: boolean }[]
        if (!lock[0]?.ok) return -1
        const now = (await tx`select n from index_meta where k = 'pages_live'`) as { n: string | number }[]
        const room = Math.min(batch, Number(now[0]?.n ?? 0) - target)
        if (room < 1) return 0
        const out = (await tx`
          with picked as (
            select id from pages order by fetched_at, id limit ${room} for update skip locked
          ), pol as (
            delete from page_policy where id in (select id from picked)
          ), del as (
            delete from pages p using picked where p.id = picked.id returning p.id
          ), live as (
            update index_meta set n = greatest(0, n - (select count(*) from del)) where k = 'pages_live'
          )
          select count(*)::int as n from del`) as { n: number }[]
        return Number(out[0]?.n ?? 0)
      })
      if (gone < 0) break // another process is trimming
      deleted += gone
      if (gone < batch) break
      await idle(0)
    }
    this.countCache = null
    this.statsCache = null
    const left = await this.count(0)
    const bytesAfter = await this.sizeBytes(0)
    return { deleted, bytesBefore, bytesAfter, done: left * perPage <= this.maxBytes, reclaims: true, liveBytes: left * perPage }
  }

  // ---- the training corpus (/api/corpus) ---------------------------------------------------

  /**
   * The top of the id space a corpus scan may cover: the newest id at least corpusLagMs old.
   * Concurrent writers commit out of id order, so the very newest ids may still have a gap
   * below them that a cursor must not run past. Bounded by the rows written in that window.
   */
  private async safeTop(tx: SQL): Promise<number> {
    const out = (await tx`
      select coalesce((select id from pages where added_at < clock_timestamp() - make_interval(secs => ${this.corpusLagMs / 1000}::float8) order by id desc limit 1), 0) as n`) as {
      n: string | number
    }[]
    return Number(out[0]?.n ?? 0)
  }

  /** As IndexStore.corpus: id order, open pages only, windows until `limit` or the time budget. */
  async corpus(query: CorpusQuery): Promise<CorpusPage> {
    const limit = Math.min(Math.max(1, Math.trunc(query.limit ?? 20)), 100)
    const textMax = Math.min(Math.max(0, Math.trunc(query.textMax ?? 24_000)), 100_000)
    const budget = query.budgetMs ?? 800
    const start = Math.max(0, Math.trunc(query.cursor ?? 0))
    const match = query.q ? corpusWebsearch(query.q) : null
    if (query.q && !match) return { items: [], next_cursor: null, resume_cursor: String(start), total_matches: 0, total_capped: false }
    return this.timed(Math.max(2_000, budget * 4), async (tx) => {
      const maxId = await this.safeTop(tx)
      // After safeTop, which walks the primary key backwards and must stay an index scan.
      if (match) await fullTextPlan(tx)
      const filters: string[] = []
      const params: Array<string | number> = []
      const bind = (value: string | number) => {
        params.push(value)
        return `$${params.length}`
      }
      // Fixed leading parameters per query shape, then the filters.
      const lead = match ? 4 : 3
      for (let i = 0; i < lead; i++) params.push(0)
      if (query.site) filters.push(`pp.site = ${bind(query.site.toLowerCase().replace(/^www\./, ''))}`)
      if (query.kind) filters.push(`pp.kind = ${bind(query.kind)}`)
      if (query.lang) filters.push(`(pp.language = ${bind(query.lang.toLowerCase())} or pp.language like ${bind(`${query.lang.toLowerCase()}-%`)})`)
      if (query.since) filters.push(`pp.fetched_at >= ${bind(query.since)}`)
      const where = filters.length ? ` and ${filters.join(' and ')}` : ''
      const ids: number[] = []
      let scannedTo = start
      const began = performance.now()
      const run = async (sqlText: string, values: Array<string | number>) => ((await tx.unsafe(sqlText, values)) as { id: string | number }[]).map((r) => Number(r.id))
      if (!match && query.site) {
        // One site: its own index, no windows needed.
        const values = [...params]
        values[0] = start
        values[1] = maxId
        values[2] = limit
        // threatcrush-disable-next-line sql-template-interpolation  only fixed column filters and "$n" placeholders are interpolated; every value is bound
        const found = await run(`select pp.id from page_policy pp where pp.train = 1 and pp.id > $1 and pp.id <= $2${where} order by pp.id limit $3`, values)
        ids.push(...found)
        // Never behind the cursor it was given: a cursor past the lagged top stays where it is.
        scannedTo = found.length === limit ? found[found.length - 1]! : Math.max(start, maxId)
      } else {
        const sqlText = match
          ? // threatcrush-disable-next-line sql-template-interpolation  only fixed column filters and "$n" placeholders are interpolated; every value is bound
            `select p.id from pages p join page_policy pp on pp.id = p.id where p.fts @@ websearch_to_tsquery('simple'::regconfig, $4) and p.id > $1 and p.id <= $2 and pp.train = 1${where} order by p.id limit $3`
          : // threatcrush-disable-next-line sql-template-interpolation  only fixed column filters and "$n" placeholders are interpolated; every value is bound
            `select pp.id from page_policy pp where pp.train = 1 and pp.id > $1 and pp.id <= $2${where} order by pp.id limit $3`
        let window = 50_000
        let lo = start
        while (lo < maxId && ids.length < limit) {
          const hi = Math.min(maxId, lo + window)
          const need = limit - ids.length
          const values = [...params]
          values[0] = lo
          values[1] = hi
          values[2] = need
          if (match) values[3] = match
          const found = await run(sqlText, values)
          ids.push(...found)
          scannedTo = found.length === need ? found[found.length - 1]! : hi
          lo = scannedTo
          if (performance.now() - began > budget) break
          if (found.length < need) window = Math.min(window * 4, 2_000_000)
        }
      }
      const items: CorpusItem[] = []
      if (ids.length) {
        const rows = (await tx`
          select id, url, title, site, kind, language, fetched_at, left(body, ${textMax}) as text
          from pages where id = any(${pgArray(ids)}::bigint[]) order by id`) as Array<CorpusItem & { id: string | number }>
        for (const r of rows) items.push({ ...r, id: Number(r.id) })
      }
      let total: number | null = null
      let capped = false
      if (match && start === 0) {
        const out = (await tx`
          select count(*)::int as n from (select 1 from pages where fts @@ websearch_to_tsquery('simple'::regconfig, ${match}) limit ${TOTAL_CAP}) t`) as { n: number }[]
        total = Number(out[0]?.n ?? 0)
        capped = total >= TOTAL_CAP
      }
      const done = scannedTo >= maxId && ids.length < limit
      return { items, next_cursor: done ? null : String(scannedTo), resume_cursor: String(scannedTo), total_matches: total, total_capped: capped }
    })
  }

  private async computeStats(now: number): Promise<Record<string, unknown>> {
    return this.timed(60_000, async (tx) => {
      const byTrain = (await tx`select train, count(*)::bigint as n from page_policy group by train`) as Array<{ train: number | null; n: string | number }>
      const n = (t: number | null) => Number(byTrain.find((r) => (r.train === null ? null : Number(r.train)) === t)?.n ?? 0)
      const sites = (await tx`select count(distinct site)::bigint as n from page_policy where train = 1`) as { n: string | number }[]
      const languages = (await tx`select coalesce(language, 'unknown') as language, count(*)::int as pages from page_policy where train = 1 group by 1 order by 2 desc limit 25`) as Array<{
        language: string
        pages: number
      }>
      const kinds = (await tx`select kind, count(*)::int as pages from page_policy where train = 1 group by 1 order by 2 desc limit 25`) as Array<{ kind: string; pages: number }>
      const reasons = (await tx`select reason, count(*)::int as pages from page_policy where train = 0 group by 1 order by 2 desc limit 25`) as Array<{ reason: string; pages: number }>
      const last = (await tx`select max(fetched_at) as t from (select fetched_at from page_policy order by id desc limit 1000) x`) as { t: string | null }[]
      const live = await this.count(0)
      return {
        pages_indexed: live,
        pages: n(1),
        excluded: n(0),
        unknown: n(null),
        not_yet_mapped: Math.max(0, live - n(1) - n(0) - n(null)),
        sites: Number(sites[0]?.n ?? 0),
        languages: languages.map((r) => ({ language: r.language, pages: Number(r.pages) })),
        kinds: kinds.map((r) => ({ kind: r.kind, pages: Number(r.pages) })),
        excluded_by: reasons.map((r) => ({ reason: r.reason, pages: Number(r.pages) })),
        last_crawl: this.lastAddAt ?? last[0]?.t ?? null,
        computed_at: new Date(now).toISOString(),
      }
    })
  }

  /**
   * Corpus counts for harvesters, cached for five minutes. Each is a scan of page_policy, so
   * once a figure exists a stale one is served while a fresh one is computed behind it.
   */
  private statsRefresh: Promise<unknown> | null = null
  async corpusStats(now = Date.now()): Promise<Record<string, unknown>> {
    if (this.statsCache && now - this.statsCache.at < 300_000) return this.statsCache.value
    if (this.statsCache) {
      this.statsRefresh ??= this.computeStats(now)
        .then((value) => (this.statsCache = { at: now, value }))
        .catch(() => {})
        .finally(() => (this.statsRefresh = null))
      return this.statsCache.value
    }
    const value = await this.computeStats(now)
    this.statsCache = { at: now, value }
    return value
  }

  // ---- backfill: pages indexed before verdicts were recorded ---------------------------

  /** Gives `n` more pages without a page_policy row one (train unknown). 0 once every page has one. */
  async mapLegacy(n = 2000): Promise<number> {
    const after = (await this.meta('map_cursor')) ?? 0
    const out = (await this.sql`
      with batch as (select id, site, kind, language, fetched_at from pages where id > ${after} order by id limit ${n}),
      ins as (
        insert into page_policy (id, site, kind, language, fetched_at, train, reason, source)
        select id, site, kind, language, fetched_at, null, null, 'legacy' from batch
        on conflict (id) do nothing
      ), cur as (
        insert into index_meta (k, n) select 'map_cursor', max(id) from batch having count(*) > 0
        on conflict (k) do update set n = excluded.n
      )
      select count(*)::int as n from batch`) as { n: number }[]
    return Number(out[0]?.n ?? 0)
  }

  async unknownSites(n = 16, now = Date.now()): Promise<string[]> {
    await this.init()
    const rows = (await this.sql`
      select distinct pp.site from page_policy pp where pp.train is null
        and not exists (select 1 from policy_site_checks c where c.site = pp.site and c.checked_at > ${now - 86_400_000})
      limit ${n}`) as Array<{ site: string }>
    return rows.map((r) => r.site)
  }

  async unknownPagesOf(site: string): Promise<PolicyRow[]> {
    await this.init()
    // threatcrush-disable-next-line sql-template-interpolation  Bun's sql tagged template binds ${} as parameters; nothing is concatenated
    const rows = (await this.sql`select pp.id, p.url from page_policy pp join pages p on p.id = pp.id where pp.site = ${site} and pp.train is null`) as Array<{ id: string | number; url: string }>
    return rows.map((r) => ({ id: Number(r.id), url: r.url }))
  }

  /** Records verdicts for unknown pages (never overrides one made at crawl time) and that the site was tried. */
  async setPolicies(site: string, verdicts: Array<{ id: number; allowed: boolean; reason: string }>, now = Date.now()): Promise<void> {
    await this.write(WRITE_TIMEOUT_MS, async (tx) => {
      if (verdicts.length)
        await tx`
          update page_policy pp set train = v.train, reason = v.reason, source = 'backfill'
          from unnest(${pgArray(verdicts.map((v) => v.id))}::bigint[], ${pgArray(verdicts.map((v) => (v.allowed ? 1 : 0)))}::smallint[], ${pgArray(verdicts.map((v) => clean(v.reason.slice(0, 120))))}::text[]) as v(id, train, reason)
          where pp.id = v.id and pp.train is null`
      await tx`insert into policy_site_checks (site, checked_at) values (${site}, ${now}) on conflict (site) do update set checked_at = excluded.checked_at`
    })
  }

  async setCard(url: string, image: string | null, price: string | null): Promise<void> {
    if (Buffer.byteLength(url) > MAX_URL_BYTES) return
    await this.init()
    // threatcrush-disable-next-line sql-template-interpolation  Bun's sql tagged template binds ${} as parameters; nothing is concatenated
    await this.sql`insert into page_cards (url, image, price) values (${clean(url)}, ${cleanOrNull(image)}, ${cleanOrNull(price)}) on conflict (url) do update set image = excluded.image, price = excluded.price`
  }

  /** Cards for these pages. A page absent from the map has never been looked at. */
  async cards(urls: string[]): Promise<Map<string, { image: string | null; price: string | null }>> {
    const out = new Map<string, { image: string | null; price: string | null }>()
    if (!urls.length) return out
    await this.init()
    // threatcrush-disable-next-line sql-template-interpolation  Bun's sql tagged template binds ${} as parameters; nothing is concatenated
    const rows = (await this.sql`select url, image, price from page_cards where url = any(${pgArray(urls.map(clean))}::text[])`) as Array<{ url: string; image: string | null; price: string | null }>
    for (const r of rows) out.set(r.url, { image: r.image, price: r.price })
    return out
  }

  /**
   * Best matches: every word if any page has them all, else any word. Title weighs most.
   * Ranks the first SEARCH_SCAN matches (ts_rank, weighted like the SQLite bm25), so a common
   * word costs a bounded amount; `score` is negated so lower is better, as bm25 was.
   */
  async search(query: string, limit = 10, kind?: string): Promise<IndexHit[]> {
    const terms = toFtsTerms(query)
    if (!terms.length) return []
    if (kind) return this.searchKind(terms, kind, limit)
    const k = Math.min(Math.max(1, limit), 50)
    const run = async (q: string) => {
      try {
        return await this.timed(
          SEARCH_TIMEOUT_MS,
          async (tx) => {
            const rows = (await tx`
            with cand as materialized (
              select id, fts from pages where fts @@ websearch_to_tsquery('simple'::regconfig, ${q}) limit ${SEARCH_SCAN}
            ), best as (
              select id, ts_rank(${WEIGHTS}::float4[], fts, websearch_to_tsquery('simple'::regconfig, ${q})) as rank from cand
              order by rank desc, id desc limit ${k}
            )
            select p.url, p.title, p.site, p.kind, p.fetched_at,
                   case when p.description <> '' then p.description else left(p.body, 300) end as summary,
                   -best.rank as score
            from best join pages p on p.id = best.id
            order by best.rank desc, best.id desc`) as IndexHit[]
            return rows.map((r) => ({ ...r, score: Number(r.score) }))
          },
          true,
        )
      } catch (error) {
        // Too slow is no answer, not an error: pit.world has other engines.
        if (isTimeout(error)) return []
        throw error
      }
    }
    const all = await run(websearchAll(terms))
    return all.length || terms.length === 1 ? all : run(websearchAny(terms))
  }

  /** As IndexStore.searchKind: KIND_SCAN matches, that kind only, most words in the title first. */
  private async searchKind(terms: string[], kind: string, limit: number): Promise<IndexHit[]> {
    const run = async (q: string) => {
      try {
        return await this.timed(
          SEARCH_TIMEOUT_MS,
          async (tx) => {
            return (await tx`
            with cand as materialized (
              select id from pages where fts @@ websearch_to_tsquery('simple'::regconfig, ${q}) limit ${KIND_SCAN}
            )
            select p.url, p.title, p.site, p.kind, p.fetched_at,
                   case when p.description <> '' then p.description else left(p.body, 300) end as summary, 0 as score
            from cand join pages p on p.id = cand.id
            where p.kind = ${kind}
            order by p.id desc limit 200`) as IndexHit[]
          },
          true,
        )
      } catch (error) {
        if (isTimeout(error)) return []
        throw error
      }
    }
    let hits = await run(websearchAll(terms))
    if (!hits.length && terms.length > 1) hits = await run(websearchAny(terms))
    const words = terms.map((t) => t.replace(/"/g, '').toLowerCase())
    const inTitle = (hit: IndexHit) => {
      const title = hit.title.toLowerCase()
      return words.filter((w) => title.includes(w)).length
    }
    return hits
      .map((hit) => ({ hit: { ...hit, score: Number(hit.score) }, n: inTitle(hit) }))
      .sort((a, b) => b.n - a.n)
      .slice(0, Math.min(Math.max(1, limit), 50))
      .map(({ hit }) => hit)
  }

  async importCursor(): Promise<number | null> {
    const value = await this.meta('import_cursor')
    return value ? value : null
  }

  async setImportCursor(cursor: number | null): Promise<void> {
    await this.setCursor('import_cursor', cursor)
  }

  async tables(): Promise<string[]> {
    await this.init()
    const rows = (await this.sql`select table_name as name from information_schema.tables where table_schema = current_schema() order by 1`) as Array<{ name: string }>
    return rows.map((r) => r.name)
  }

  /** The highest id in use (the primary key's last entry: no scan). */
  async highWaterMark(): Promise<number> {
    await this.init()
    const out = (await this.sql`select coalesce(max(id), 0) as n from pages`) as { n: string | number }[]
    return Number(out[0]?.n ?? 0)
  }

  async close(): Promise<void> {
    await this.refreshing?.catch(() => {})
    await this.sql.close()
  }
}

/** CRAWL_INDEX_DATABASE_URL set: Postgres, many writers. Unset: the SQLite file at indexPath. */
export function openIndex(config: { indexPath: string; indexMaxBytes: number; indexDatabaseUrl: string }): SearchIndex {
  return config.indexDatabaseUrl ? new PgIndexStore(config.indexDatabaseUrl, config.indexMaxBytes) : new IndexStore(config.indexPath, config.indexMaxBytes)
}
